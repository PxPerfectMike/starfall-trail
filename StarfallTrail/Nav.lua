-- Public: route requests
---------------------------------------------------------------------------

local job       -- running coroutine
Nav.route = nil -- { points = {{x, y}, ...}, heights, instance, goalX, goalY, expansions }

-- Starts a route search; the result lands in Nav.route when finished. `pz` (optional) is the
-- player's height, to pick the right level where walkways overlap.
function Nav.Request(px, py, tx, ty, instance, pz)
	local m = MeshFor(px, py, instance)
	if not m or MeshFor(tx, ty, instance) ~= m then
		Nav.route = nil
		job = nil
		return false
	end
	local start, _, sx, sy = FindPoly(m, px, py, pz, 8)
	local goal, _, gx, gy = FindPoly(m, tx, ty, pz, 30, start and CompOf(m, start.id))
	if not start or not goal then
		Nav.route = nil
		job = nil
		Nav.lastError = "no walkable area at the " .. (start and "target" or "start")
		return false
	end
	if CompOf(m, start.id) ~= CompOf(m, goal.id) then
		Nav.route = nil
		job = nil
		Nav.lastError = "no walkable connection to the target"
		return false
	end
	Nav.lastError = nil
	job = coroutine.create(function()
		local started = debugprofilestop and debugprofilestop()
		local field = CoarseField(m, gx, gy)
		if field and not CoarseReachable(m, field, sx, sy) then
			Nav.lastError = "no walkable connection to the target"
			return nil, 0
		end
		local path, edges, expansions = AStar(m, start, sx, sy, goal, gx, gy, field)
		if not path then
			return nil, expansions
		end
		-- path[1] is the goal, path[#path] the start; edges[i] is the edge of path[i + 1] into path[i].
		local corridor, portals = {}, {}
		for n = #path, 1, -1 do
			corridor[#corridor + 1] = Poly(m, path[n])
		end
		for n = 1, #corridor - 1 do
			local a = corridor[n]
			local e = edges[#path - n]
			local x1, y1, _, x2, y2 = Portal(m, a, e)
			-- Left and right as seen walking through the portal from a's center.
			if TriArea2(a.cx, a.cy, x1, y1, x2, y2) > 0 then
				portals[#portals + 1] = { x1, y1, x2, y2 }
			else
				portals[#portals + 1] = { x2, y2, x1, y1 }
			end
		end
		portals[#portals + 1] = { gx, gy, gx, gy }
		local corners = Funnel(sx, sy, portals)
		corners[1] = { px, py }
		corners[#corners] = { tx, ty }
		local points = Resample(Chaikin(Resample(corners, SAMPLE_SPACING), 2), SAMPLE_SPACING)
		-- Heights from the corridor polygons, walking forward along it.
		local heights = {}
		local c = 1
		local lastH = pz
		for n, pt in ipairs(points) do
			local h
			for k = c, min(#corridor, c + 12) do
				local hh = HeightInPoly(corridor[k], pt[1], pt[2])
				if hh then
					h, c = hh, k
					break
				end
			end
			if not h then
				local _, hh = FindPoly(m, pt[1], pt[2], lastH, 4)
				h = hh or lastH or corridor[c].zs[1]
			end
			heights[n] = h
			lastH = h
		end
		-- The polygons are flat pieces up to ~3 yards off the true terrain, so raw heights step at
		-- every polygon edge, and the whole trail jumps as you cross one. Two passes of a wide
		-- triangle filter (about +-10 yards) along the route turn the steps into gentle slopes.
		for _ = 1, 2 do
			local src = {}
			for n = 1, #heights do
				src[n] = heights[n]
			end
			for n = 1, #heights do
				local sum, weight = 0, 0
				for k = -HEIGHT_SMOOTH, HEIGHT_SMOOTH do
					local v = src[n + k]
					if v then
						local w = HEIGHT_SMOOTH + 1 - math.abs(k)
						sum, weight = sum + v * w, weight + w
					end
				end
				heights[n] = sum / weight
			end
		end
		local ms = started and (debugprofilestop() - started) or 0
		return { points = points, heights = heights, instance = instance, goalX = tx, goalY = ty,
			expansions = expansions, ms = ms, polys = #corridor }
	end)
	return true
end

-- Advances the running search by one slice; call once per frame.
function Nav.Step()
	if not job then
		return
	end
	local ok, result, extra = coroutine.resume(job)
	if not ok then
		job = nil
		Nav.route = nil
		Nav.lastError = tostring(result)
		return
	end
	if coroutine.status(job) == "dead" then
		job = nil
		Nav.route = result
		Nav.lastExpansions = result and result.expansions or extra
		if not result and extra ~= 0 then
			Nav.lastError = "no path"
		end
	end
end

function Nav.Busy()
	return job ~= nil
end

function Nav.Clear()
	job = nil
	Nav.route = nil
end
