-- A* over polygons
---------------------------------------------------------------------------

-- Portal (shared edge) from polygon a to its neighbor across edge e (1-based), clipped where the
-- neighbor only covers part of the edge (tile borders).
local function Portal(m, a, e)
	local f = e % a.n + 1
	local x1, y1, z1, x2, y2, z2 = a.xs[e], a.ys[e], a.zs[e], a.xs[f], a.ys[f], a.zs[f]
	local clip = m.clips[a.id * 8 + (e - 1)]
	if clip then
		local t0, t1 = clip[1], clip[2]
		x1, y1, z1, x2, y2, z2 =
			x1 + (x2 - x1) * t0, y1 + (y2 - y1) * t0, z1 + (z2 - z1) * t0,
			x1 + (x2 - x1) * t1, y1 + (y2 - y1) * t1, z1 + (z2 - z1) * t1
	end
	return x1, y1, z1, x2, y2, z2
end

-- `field` (optional) is the coarse cost field toward the goal: the search then heads straight down
-- the cheapest corridor instead of spreading out, which keeps long routes fast.
local function AStar(m, start, sx, sy, goal, gx, gy, field)
	local cellSize, cx0, cy0, ncx, ncy = m.cell, m.x0, m.y0, m.ncx, m.ncy
	local function H(x, y)
		local e = sqrt((gx - x) ^ 2 + (gy - y) ^ 2) * ROAD_COST
		if field then
			local i, j = floor((x - cx0) / cellSize), floor((y - cy0) / cellSize)
			if i >= 0 and j >= 0 and i < ncx and j < ncy then
				local f = field[j * ncx + i]
				if f and f > e then
					return f
				end
			end
		end
		return e
	end

	local g, came, cameEdge = { [start.id] = 0 }, {}, {}
	local posX, posY, closed = { [start.id] = sx }, { [start.id] = sy }, {}
	local heapK, heapF, size = { start.id }, { 0 }, 1

	local function Push(k, f)
		size = size + 1
		local n = size
		heapK[n], heapF[n] = k, f
		while n > 1 do
			local p = floor(n / 2)
			if heapF[p] <= heapF[n] then
				break
			end
			heapK[p], heapK[n] = heapK[n], heapK[p]
			heapF[p], heapF[n] = heapF[n], heapF[p]
			n = p
		end
	end

	local function Pop()
		local k = heapK[1]
		heapK[1], heapF[1] = heapK[size], heapF[size]
		heapK[size], heapF[size] = nil, nil
		size = size - 1
		local n = 1
		while true do
			local l, r, s = n * 2, n * 2 + 1, n
			if l <= size and heapF[l] < heapF[s] then s = l end
			if r <= size and heapF[r] < heapF[s] then s = r end
			if s == n then
				break
			end
			heapK[s], heapK[n] = heapK[n], heapK[s]
			heapF[s], heapF[n] = heapF[n], heapF[s]
			n = s
		end
		return k
	end

	local expansions = 0
	while size > 0 do
		local k = Pop()
		if k == goal.id then
			local path, edges = {}, {}
			while k do
				path[#path + 1] = k
				edges[#edges + 1] = cameEdge[k] or false
				k = came[k]
			end
			return path, edges, expansions
		end
		if not closed[k] then
			closed[k] = true
			expansions = expansions + 1
			if expansions > MAX_EXPANSIONS then
				return nil, nil, expansions
			end
			if expansions % EXPANSIONS_PER_SLICE == 0 then
				coroutine.yield()
			end
			local poly = Poly(m, k)
			local rate = COST[poly.code]
			local px, py, gk = posX[k], posY[k], g[k]
			for e = 1, poly.n do
				local nb = poly.nbs[e]
				if nb and not closed[nb] then
					-- Enter the neighbor at the middle of the shared portal.
					local x1, y1, _, x2, y2 = Portal(m, poly, e)
					local mx, my = (x1 + x2) * 0.5, (y1 + y2) * 0.5
					local ng = gk + sqrt((mx - px) ^ 2 + (my - py) ^ 2) * rate
					if nb == goal.id then
						ng = ng + sqrt((gx - mx) ^ 2 + (gy - my) ^ 2) * COST[goal.code]
					end
					if not g[nb] or ng < g[nb] then
						g[nb] = ng
						came[nb] = k
						cameEdge[nb] = e
						posX[nb], posY[nb] = mx, my
						Push(nb, ng + H(mx, my))
					end
				end
			end
		end
	end
	return nil, nil, expansions
end

---------------------------------------------------------------------------
-- Funnel (string pulling through the polygon corridor) and smoothing
---------------------------------------------------------------------------

local function TriArea2(ax, ay, bx, by, cx, cy)
	return (cx - ax) * (by - ay) - (bx - ax) * (cy - ay)
end

-- portals: list of { lx, ly, rx, ry } from start to goal (the last is the goal point twice).
local function Funnel(sx, sy, portals)
	local out = { { sx, sy } }
	local apexX, apexY = sx, sy
	local leftX, leftY, rightX, rightY = sx, sy, sx, sy
	local apexIndex, leftIndex, rightIndex = 0, 0, 0
	local i = 1
	local guard = 0
	while i <= #portals do
		guard = guard + 1
		if guard > 50000 then
			break
		end
		local p = portals[i]
		local lx, ly, rx, ry = p[1], p[2], p[3], p[4]
		local restart = false
		-- Narrow the right side.
		if TriArea2(apexX, apexY, rightX, rightY, rx, ry) <= 0 then
			if (apexX == rightX and apexY == rightY) or TriArea2(apexX, apexY, leftX, leftY, rx, ry) > 0 then
				rightX, rightY, rightIndex = rx, ry, i
			else
				-- Right crossed left: the left corner becomes a path point.
				out[#out + 1] = { leftX, leftY }
				apexX, apexY, apexIndex = leftX, leftY, leftIndex
				leftX, leftY, rightX, rightY = apexX, apexY, apexX, apexY
				leftIndex, rightIndex = apexIndex, apexIndex
				i = apexIndex + 1
				restart = true
			end
		end
		if not restart then
			-- Narrow the left side.
			if TriArea2(apexX, apexY, leftX, leftY, lx, ly) >= 0 then
				if (apexX == leftX and apexY == leftY) or TriArea2(apexX, apexY, rightX, rightY, lx, ly) < 0 then
					leftX, leftY, leftIndex = lx, ly, i
				else
					out[#out + 1] = { rightX, rightY }
					apexX, apexY, apexIndex = rightX, rightY, rightIndex
					leftX, leftY, rightX, rightY = apexX, apexY, apexX, apexY
					leftIndex, rightIndex = apexIndex, apexIndex
					i = apexIndex + 1
					restart = true
				end
			end
		end
		if not restart then
			i = i + 1
		end
	end
	local last = portals[#portals]
	local tail = out[#out]
	if tail[1] ~= last[1] or tail[2] ~= last[2] then
		out[#out + 1] = { last[1], last[2] }
	end
	return out
end

-- Even spacing along the polyline.
local function Resample(points, spacing)
	local out = { { points[1][1], points[1][2] } }
	local carry = 0
	for n = 1, #points - 1 do
		local ax, ay = points[n][1], points[n][2]
		local bx, by = points[n + 1][1], points[n + 1][2]
		local len = sqrt((bx - ax) ^ 2 + (by - ay) ^ 2)
		local d = spacing - carry
		while d <= len do
			local t = d / len
			out[#out + 1] = { ax + (bx - ax) * t, ay + (by - ay) * t }
			d = d + spacing
		end
		carry = len - (d - spacing)
	end
	local last = points[#points]
	local tail = out[#out]
	if (tail[1] - last[1]) ^ 2 + (tail[2] - last[2]) ^ 2 > 0.01 then
		out[#out + 1] = { last[1], last[2] }
	end
	return out
end

-- Chaikin corner cutting, keeping both endpoints. Run on short segments only, so a corner is
-- rounded by well under a yard and never cut through a wall.
local function Chaikin(points, passes)
	for _ = 1, passes do
		local out = { points[1] }
		for n = 1, #points - 1 do
			local p, q = points[n], points[n + 1]
			out[#out + 1] = { p[1] * 0.75 + q[1] * 0.25, p[2] * 0.75 + q[2] * 0.25 }
			out[#out + 1] = { p[1] * 0.25 + q[1] * 0.75, p[2] * 0.25 + q[2] * 0.75 }
		end
		out[#out + 1] = points[#points]
		points = out
	end
	return points
end

