-- Starfall Trail navigation over a walkable-area mesh (polygons extracted from the game's own collision
-- data by tools/build_navmesh.py), so bridges, ramps, walls, trees and fences are exact.
-- World coordinates follow HereBeDragons (x grows west, y grows north).
--
-- A* runs over polygons (a coroutine slice per frame), the polygon corridor is straightened with
-- the funnel algorithm, then corners are rounded gently and the path resampled every 2.5 yards.

local _, ns = ...

local Nav = {}
ns.Nav = Nav

local B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
local DECODE = {}
for i = 1, #B64 do
	DECODE[B64:byte(i)] = i - 1
end

local byte, sqrt, floor, abs, max, min = string.byte, math.sqrt, math.floor, math.abs, math.max, math.min

local EXPANSIONS_PER_SLICE = 400    -- polygons per frame
local MAX_EXPANSIONS = 120000
local SAMPLE_SPACING = 2.5          -- yards between output path points
local HEIGHT_SMOOTH = 4             -- route points each side used to smooth route heights
local ROAD_COST = 4                 -- cheapest polygon cost (roads), also the heuristic's rate

---------------------------------------------------------------------------
-- Mesh access
---------------------------------------------------------------------------

local function D3(s, p)
	local a, b, c = byte(s, p, p + 2)
	return (DECODE[a] * 64 + DECODE[b]) * 64 + DECODE[c]
end

local function D4(s, p)
	local a, b, c, d = byte(s, p, p + 3)
	return ((DECODE[a] * 64 + DECODE[b]) * 64 + DECODE[c]) * 64 + DECODE[d]
end

-- Record k (0-based) of a chunked string list: the chunk string and the record's first position.
local function Rec(m, list, k, width)
	local c = floor(k / m.chunk)
	return list[c + 1], (k - c * m.chunk) * width + 1
end

-- Road preference: costs above road cost are stretched by this factor.
local COST = {}
function Nav.SetOffroadFactor(factor)
	Nav.offroadFactor = factor
	for code = 0, 63 do
		COST[code] = code <= ROAD_COST and ROAD_COST or ROAD_COST + (code - ROAD_COST) * factor
	end
end
Nav.SetOffroadFactor(3)

-- Decoded polygons, cached per mesh: { n, code, xs, ys, zs, nbs (0-based ids or false), cx, cy, id }.
local cache = {}

local cached = 0
local CACHE_LIMIT = 30000   -- decoded polygons kept (about 10 MB); start over past this

local function Poly(m, k)
	local polys = cache[m]
	if not polys or cached > CACHE_LIMIT then
		polys = {}
		cache[m] = polys
		cached = 0
	end
	local poly = polys[k]
	if poly then
		return poly
	end
	cached = cached + 1
	local ps, p = Rec(m, m.polys, k, 7)
	local a, b, c, d, e = byte(ps, p, p + 4)
	local first = (((DECODE[a] * 64 + DECODE[b]) * 64 + DECODE[c]) * 64 + DECODE[d]) * 64 + DECODE[e]
	local n = DECODE[byte(ps, p + 5)]
	local code = DECODE[byte(ps, p + 6)]
	local xs, ys, zs, nbs = {}, {}, {}, {}
	local q = m.quant
	for e = 0, n - 1 do
		local es, ep = Rec(m, m.edges, first + e, 8)
		local v = D4(es, ep)
		local nb = D4(es, ep + 4)
		local vs, vp = Rec(m, m.verts, v, 9)
		xs[e + 1] = m.x0 + D3(vs, vp) / q
		ys[e + 1] = m.y0 + D3(vs, vp + 3) / q
		zs[e + 1] = m.z0 + D3(vs, vp + 6) / q
		nbs[e + 1] = nb > 0 and nb - 1 or false
	end
	local cx, cy = 0, 0
	for e = 1, n do
		cx, cy = cx + xs[e], cy + ys[e]
	end
	poly = { n = n, code = code, xs = xs, ys = ys, zs = zs, nbs = nbs, cx = cx / n, cy = cy / n, id = k }
	polys[k] = poly
	return poly
end

-- Each continent's mesh ships as its own load-on-demand addon (generated by build_navmesh.py),
-- loaded the first time it is needed and registered in the global StarfallTrailMeshes.
local MESH_ADDONS = {
	[0] = "StarfallTrail_EasternKingdoms",
	[1] = "StarfallTrail_Kalimdor",
}
local loadTried = {}

local function LoadMesh(instance)
	StarfallTrailMeshes = StarfallTrailMeshes or {}
	local m = StarfallTrailMeshes[instance]
	if m or loadTried[instance] then
		return m
	end
	loadTried[instance] = true
	local addon = MESH_ADDONS[instance]
	if not addon then
		return nil
	end
	local load = (C_AddOns and C_AddOns.LoadAddOn) or LoadAddOn
	local started = debugprofilestop and debugprofilestop()
	local ok, loaded, reason = pcall(load, addon)
	if not ok or not loaded then
		Nav.loadError = addon .. ": " .. tostring(ok and reason or loaded)
		return nil
	end
	m = StarfallTrailMeshes[instance]
	if m and started then
		Nav.loadMs = debugprofilestop() - started
	end
	return m
end
Nav.LoadMesh = LoadMesh

local function MeshFor(x, y, instance)
	local m = instance and LoadMesh(instance)
	if m and x >= m.x0 and y >= m.y0 and x < m.x0 + m.nbx * m.bucket and y < m.y0 + m.nby * m.bucket then
		return m
	end
	return nil
end
-- Kept under its old name: the trail asks it whether a place has navigation data.
Nav.GridFor = MeshFor

-- Height of the polygon's surface at (x, y), or nil when the point is outside it.
local function HeightInPoly(poly, x, y)
	local xs, ys, zs, n = poly.xs, poly.ys, poly.zs, poly.n
	-- Point-in-convex-polygon, independent of winding.
	local sign = 0
	for e = 1, n do
		local f = e % n + 1
		local cross = (xs[f] - xs[e]) * (y - ys[e]) - (ys[f] - ys[e]) * (x - xs[e])
		if cross > 1e-7 then
			if sign < 0 then return nil end
			sign = 1
		elseif cross < -1e-7 then
			if sign > 0 then return nil end
			sign = -1
		end
	end
	-- Height from the fan triangle that holds the point.
	for e = 2, n - 1 do
		local ax, ay, bx, by, cx, cy = xs[1], ys[1], xs[e], ys[e], xs[e + 1], ys[e + 1]
		local d = (by - cy) * (ax - cx) + (cx - bx) * (ay - cy)
		if abs(d) > 1e-9 then
			local u = ((by - cy) * (x - cx) + (cx - bx) * (y - cy)) / d
			local v = ((cy - ay) * (x - cx) + (ax - cx) * (y - cy)) / d
			if u >= -1e-4 and v >= -1e-4 and u + v <= 1 + 1e-4 then
				return u * zs[1] + v * zs[e] + (1 - u - v) * zs[e + 1]
			end
		end
	end
	return (zs[1] + zs[2] + zs[n]) / 3
end

-- Closest point of the polygon's outline to (x, y), as (squared distance, px, py, pz).
local function ClosestOnPoly(poly, x, y)
	local xs, ys, zs, n = poly.xs, poly.ys, poly.zs, poly.n
	local best, bx, by, bz = math.huge, nil, nil, nil
	for e = 1, n do
		local f = e % n + 1
		local ex, ey = xs[f] - xs[e], ys[f] - ys[e]
		local len2 = ex * ex + ey * ey
		local t = len2 > 0 and max(0, min(1, ((x - xs[e]) * ex + (y - ys[e]) * ey) / len2)) or 0
		local qx, qy = xs[e] + ex * t, ys[e] + ey * t
		local d = (qx - x) ^ 2 + (qy - y) ^ 2
		if d < best then
			best, bx, by, bz = d, qx, qy, zs[e] + (zs[f] - zs[e]) * t
		end
	end
	return best, bx, by, bz
end

local function BucketPolys(m, bx, by, out)
	if bx < 0 or by < 0 or bx >= m.nbx or by >= m.nby then
		return
	end
	local b = by * m.nbx + bx
	local from = D4(Rec(m, m.bucketStart, b, 4))
	local to = D4(Rec(m, m.bucketStart, b + 1, 4))
	for i = from, to - 1 do
		out[#out + 1] = D4(Rec(m, m.bucketItems, i, 4))
	end
end

-- Ground-surface height near (x, y) from the coarse terrain samples: the guess for which level you
-- stand on before any height is known (not a tunnel below, not a walkway above).
local function GroundHint(m, x, y)
	local bx = floor((x - m.x0) / m.bucket)
	local by = floor((y - m.y0) / m.bucket)
	if bx < 0 or by < 0 or bx >= m.nbx or by >= m.nby then
		return nil
	end
	local s, p = Rec(m, m.ground, by * m.nbx + bx, 2)
	local a, b = byte(s, p, p + 1)
	local v = DECODE[a] * 64 + DECODE[b]
	return v > 0 and m.z0 - 100 + v or nil
end

-- The polygon under (x, y): when several layers overlap (a bridge over a path), the one nearest
-- height `z`; without `z`, the one nearest the ground surface. Off the mesh (inside a tree trunk, a
-- wall), the closest walkable spot within `reach` yards. Returns polygon, height, x, y (snapped).
-- Connected piece of the mesh a polygon id belongs to (0 when the data has none).
local function CompOf(m, k)
	if not m.comps then
		return 0
	end
	local s, p = Rec(m, m.comps, k, 2)
	local a, b = byte(s, p, p + 1)
	return DECODE[a] * 64 + DECODE[b]
end

-- `comp` (optional): prefer polygons in that connected piece, e.g. the start's piece when placing the goal.
local function FindPoly(m, x, y, z, reach, comp)
	z = z or GroundHint(m, x, y)
	local function Other(k)
		return comp and CompOf(m, k) ~= comp and 1e7 or 0
	end
	local bx = floor((x - m.x0) / m.bucket)
	local by = floor((y - m.y0) / m.bucket)
	local list = {}
	BucketPolys(m, bx, by, list)
	local best, bestH, bestScore
	for _, k in ipairs(list) do
		local poly = Poly(m, k)
		local h = HeightInPoly(poly, x, y)
		if h then
			local score = (z and abs(h - z) or h) + Other(k)
			if not bestScore or score < bestScore then
				best, bestH, bestScore = poly, h, score
			end
		end
	end
	if best and (bestScore < 1e7 or not reach or reach <= 0) then
		return best, bestH, x, y
	end
	local under, underH = best, bestH
	if not reach or reach <= 0 then
		return nil
	end
	local r = math.ceil(reach / m.bucket)
	list = {}
	for dy = -r, r do
		for dx = -r, r do
			BucketPolys(m, bx + dx, by + dy, list)
		end
	end
	local bestD, snapX, snapY
	local seen = {}
	for _, k in ipairs(list) do
		if not seen[k] then
			seen[k] = true
			local poly = Poly(m, k)
			local d, qx, qy, qz = ClosestOnPoly(poly, x, y)
			local score = d + Other(k)
			if z then
				score = score + ((qz - z) * 0.5) ^ 2   -- prefer the same level
			end
			if d <= reach * reach and (not bestD or score < bestD) then
				best, bestD, bestH, snapX, snapY = poly, score, qz, qx, qy
			end
		end
	end
	if under and (not bestD or bestD >= 1e7) then
		return under, underH, x, y
	end
	if bestD then
		return best, bestH, snapX, snapY
	end
	return nil
end

-- Surface height at a world point (nil off the mesh). `ref` picks the layer nearest that height.
function Nav.HeightAtWorld(x, y, instance, ref)
	local m = MeshFor(x, y, instance)
	if not m then
		return nil
	end
	local _, h = FindPoly(m, x, y, ref, 3)
	return h
end

---------------------------------------------------------------------------
-- Coarse cells: a cost field toward the goal for long routes
---------------------------------------------------------------------------

-- The 8 directions of a cell's neighbor bits: E, NE, N, NW, W, SW, S, SE.
local DIR_X = { 1, 1, 0, -1, -1, -1, 0, 1 }
local DIR_Y = { 0, 1, 1, 1, 0, -1, -1, -1 }
local CELL_PER_SLICE = 3000

local function CellAt(m, x, y)
	local i = floor((x - m.x0) / m.cell)
	local j = floor((y - m.y0) / m.cell)
	if i < 0 or j < 0 or i >= m.ncx or j >= m.ncy then
		return nil
	end
	return j * m.ncx + i, i, j
end

local function CellInfo(m, c)
	local s, p = Rec(m, m.cells, c, 3)
	local a, b, d = byte(s, p, p + 2)
	return DECODE[a], DECODE[b] * 64 + DECODE[d]
end

-- Cheapest travel cost from every reachable cell to the goal's cell (Dijkstra over the cells).
-- Cached per goal cell: re-routes toward the same target reuse it.
local coarse = { mesh = nil, cell = nil, field = nil, factor = nil }

local function CoarseField(m, gx, gy)
	if not m.cells then
		return nil
	end
	local goal = CellAt(m, gx, gy)
	if not goal then
		return nil
	end
	if coarse.mesh == m and coarse.cell == goal and coarse.factor == Nav.offroadFactor then
		return coarse.field
	end
	local field = { [goal] = 0 }
	local heapK, heapF, size = { goal }, { 0 }, 1
	local pops = 0
	while size > 0 do
		local c, f = heapK[1], heapF[1]
		heapK[1], heapF[1] = heapK[size], heapF[size]
		heapK[size], heapF[size] = nil, nil
		size = size - 1
		local n = 1
		while true do
			local l, r, s = n * 2, n * 2 + 1, n
			if l <= size and heapF[l] < heapF[s] then s = l end
			if r <= size and heapF[r] < heapF[s] then s = r end
			if s == n then
				break
			end
			heapK[s], heapK[n] = heapK[n], heapK[s]
			heapF[s], heapF[n] = heapF[n], heapF[s]
			n = s
		end
		if f <= field[c] then
			pops = pops + 1
			if pops % CELL_PER_SLICE == 0 then
				coroutine.yield()
			end
			local code, bits = CellInfo(m, c)
			local rate = COST[code > 0 and code or 10]
			local i, j = c % m.ncx, floor(c / m.ncx)
			for k = 1, 8 do
				if floor(bits / 2 ^ (k - 1)) % 2 == 1 then
					local ni, nj = i + DIR_X[k], j + DIR_Y[k]
					if ni >= 0 and nj >= 0 and ni < m.ncx and nj < m.ncy then
						local nc = nj * m.ncx + ni
						local ncode = CellInfo(m, nc)
						local step = (k % 2 == 0) and 1.41421356 or 1
						local nf = f + step * m.cell * (rate + COST[ncode > 0 and ncode or 10]) * 0.5
						if not field[nc] or nf < field[nc] then
							field[nc] = nf
							size = size + 1
							local q = size
							heapK[q], heapF[q] = nc, nf
							while q > 1 do
								local p = floor(q / 2)
								if heapF[p] <= heapF[q] then
									break
								end
								heapK[p], heapK[q] = heapK[q], heapK[p]
								heapF[p], heapF[q] = heapF[q], heapF[p]
								q = p
							end
						end
					end
				end
			end
		end
	end
	coarse.mesh, coarse.cell, coarse.field, coarse.factor = m, goal, field, Nav.offroadFactor
	return field
end

-- Whether the start's cell (or one next to it) connects to the goal in the coarse cells.
local function CoarseReachable(m, field, x, y)
	local c, i, j = CellAt(m, x, y)
	if not c then
		return false
	end
	for dj = -1, 1 do
		for di = -1, 1 do
			local ni, nj = i + di, j + dj
			if ni >= 0 and nj >= 0 and ni < m.ncx and nj < m.ncy and field[nj * m.ncx + ni] then
				return true
			end
		end
	end
	return false
end

